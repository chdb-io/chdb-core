static void test_cancel_then_destroy(chdb_connection conn)
{
    printf("== test_cancel_then_destroy ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st4 (a UInt64) ENGINE = Memory"));

    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st4 (a)", "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");
    CHECK(chdb_stream_append(stream, "1\n", 2) == CHDBSuccess, "append before cancel");

    chdb_stream_cancel_insert(stream);
    /* cancel is idempotent: a second cancel must be a harmless no-op. */
    chdb_stream_cancel_insert(stream);
    chdb_destroy_insert_stream(stream);

    /* Unfinalized single-block insert commits nothing, and the connection
     * must remain usable for both queries and a fresh insert stream. */
    expect_query(conn, "SELECT count() FROM st4", "0\n");

    chdb_insert_stream stream2 = chdb_stream_insert(conn, "INSERT INTO st4 (a)", "CSV");
    CHECK(stream2 != NULL && chdb_stream_insert_error(stream2) == NULL, "new stream after cancel");
    CHECK(chdb_stream_append(stream2, "7\n", 2) == CHDBSuccess, "append on new stream");
    chdb_result * result = chdb_stream_done(stream2);
    if (result) {
        CHECK(chdb_result_rows_written(result) == 1, "rows_written == 1 after re-insert");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream2);

    expect_query(conn, "SELECT a FROM st4", "7\n");
}

static void test_destroy_without_finalize(chdb_connection conn)
{
    printf("== test_destroy_without_finalize ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st10 (a UInt64) ENGINE = Memory"));

    /* Destroying a live stream with neither done() nor cancel() must
     * internally cancel it (the C analog of Python's `with` block exiting
     * without finish()): nothing is committed, nothing leaks, and the
     * connection stays usable. */
    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st10 (a)", "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");
    CHECK(chdb_stream_append(stream, "1\n2\n", 4) == CHDBSuccess, "append");
    chdb_destroy_insert_stream(stream);

    expect_query(conn, "SELECT count() FROM st10", "0\n");

    /* The single-active-statement slot must have been released. */
    chdb_insert_stream stream2 = chdb_stream_insert(conn, "INSERT INTO st10 (a)", "CSV");
    CHECK(stream2 != NULL && chdb_stream_insert_error(stream2) == NULL,
          "new stream after destroy-without-finalize");
    CHECK(chdb_stream_append(stream2, "5\n", 2) == CHDBSuccess, "append on new stream");
    chdb_result * result = chdb_stream_done(stream2);
    if (result) {
        CHECK(chdb_result_rows_written(result) == 1, "rows_written == 1");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream2);
    expect_query(conn, "SELECT a FROM st10", "5\n");
}

static void test_null_argument_hardening(void)
{
    printf("== test_null_argument_hardening ==\n");

    CHECK(chdb_stream_append(NULL, "1\n", 2) == CHDBError, "append(NULL) fails");
    CHECK(chdb_stream_insert_error(NULL) == NULL, "error(NULL) is NULL");
    chdb_stream_cancel_insert(NULL);   /* must be a no-op, not a crash */
    chdb_destroy_insert_stream(NULL);  /* must be a no-op, not a crash */

    chdb_result * result = chdb_stream_done(NULL);
    CHECK(result != NULL, "done(NULL) returns an error result");
    if (result) {
        CHECK(chdb_result_error(result) != NULL, "done(NULL) reports an error");
        chdb_destroy_query_result(result);
    }

    /* NULL connection: handle is non-NULL and carries the error. */
    chdb_insert_stream stream = chdb_stream_insert(NULL, "INSERT INTO t (a)", "CSV");
    CHECK(stream != NULL, "insert(NULL conn) returns a handle");
    if (stream) {
        CHECK(chdb_stream_insert_error(stream) != NULL, "insert(NULL conn) carries an error");
        chdb_destroy_insert_stream(stream);
    }
}

