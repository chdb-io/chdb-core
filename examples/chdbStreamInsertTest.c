static void test_post_done_contract(chdb_connection conn)
{
    printf("== test_post_done_contract ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st6 (a UInt64) ENGINE = Memory"));

    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st6 (a)", "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");
    CHECK(chdb_stream_append(stream, "1\n", 2) == CHDBSuccess, "append before done");

    chdb_result * result = chdb_stream_done(stream);
    if (result) {
        CHECK(chdb_result_error(result) == NULL, "first done ok");
        chdb_destroy_query_result(result);
    }

    /* Appending to a finalized stream must fail cleanly. */
    CHECK(chdb_stream_append(stream, "2\n", 2) == CHDBError, "append after done fails");

    /* A second done must report an error, not commit or crash. */
    chdb_result * result2 = chdb_stream_done(stream);
    CHECK(result2 != NULL, "second done returns a result");
    if (result2) {
        CHECK(chdb_result_error(result2) != NULL, "second done reports an error");
        chdb_destroy_query_result(result2);
    }
    chdb_destroy_insert_stream(stream);

    expect_query(conn, "SELECT count() FROM st6", "1\n");
}

static void test_malformed_row_error(chdb_connection conn)
{
    printf("== test_malformed_row_error ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st7 (a UInt64) ENGINE = Memory"));

    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st7 (a)", "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");

    /* Parsing happens asynchronously on the worker: the failure may surface
     * on this append or at done(), but no later — and nothing is committed. */
    chdb_state append_state = chdb_stream_append(stream, "abc\n", 4);

    chdb_result * result = chdb_stream_done(stream);
    CHECK(result != NULL, "done returns a result");
    int error_surfaced = (append_state == CHDBError);
    if (result) {
        if (chdb_result_error(result) != NULL)
            error_surfaced = 1;
        chdb_destroy_query_result(result);
    }
    CHECK(error_surfaced, "malformed row error surfaced by done() at latest");
    chdb_destroy_insert_stream(stream);

    expect_query(conn, "SELECT count() FROM st7", "0\n");
}

static void test_concurrent_statement_rejected(chdb_connection conn)
{
    printf("== test_concurrent_statement_rejected ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st8 (a UInt64) ENGINE = Memory"));

    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st8 (a)", "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");
    CHECK(chdb_stream_append(stream, "1\n", 2) == CHDBSuccess, "append");

    /* Single-active-statement: a query while the stream is open must be
     * rejected with an error result, not run. */
    chdb_result * blocked = chdb_query(conn, "SELECT 1", "CSV");
    CHECK(blocked != NULL, "query returns a result");
    if (blocked) {
        CHECK(chdb_result_error(blocked) != NULL, "query while insert active is rejected");
        chdb_destroy_query_result(blocked);
    }

    /* A second insert stream must be rejected too. */
    chdb_insert_stream stream2 = chdb_stream_insert(conn, "INSERT INTO st8 (a)", "CSV");
    CHECK(stream2 != NULL, "second stream handle non-NULL");
    if (stream2) {
        CHECK(chdb_stream_insert_error(stream2) != NULL, "second concurrent stream is rejected");
        chdb_destroy_insert_stream(stream2);
    }

    chdb_result * result = chdb_stream_done(stream);
    if (result) {
        CHECK(chdb_result_error(result) == NULL, "done ok after rejected attempts");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream);

    /* Connection works again after finish. */
    expect_query(conn, "SELECT count() FROM st8", "1\n");
}

