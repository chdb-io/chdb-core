/**
 * chdbStreamInsertTest.c
 *
 * Native C test for the streaming INSERT API (chdb_stream_insert family) —
 * the write-side dual of chdb_stream_query. Coverage mirrors the Python-level
 * suite (tests/test_streaming_insert*.py) minus Python-specific semantics,
 * plus C-only NULL-argument hardening.
 *
 * Verifies:
 *   1.  Full lifecycle: insert -> append -> done reports rows/bytes written,
 *       and the data reads back with exact values.
 *   2.  Input-format matrix: TSV, JSONEachRow (regression for the
 *       parallel-parsing init hang), Values.
 *   3.  True multi-chunk streaming: 20k one-row appends — exact count/sum.
 *   4.  True multi-block streaming: small insert-block SETTINGS make the
 *       worker push multiple blocks (>= 2 MergeTree parts) incrementally.
 *   5.  Appends are binary-safe: only `len` bytes are consumed.
 *   6.  Empty stream: done() after zero appends commits zero rows.
 *   7.  Post-done contract: append fails with CHDBError, a second done()
 *       reports "already finalized", destroy stays safe.
 *   8.  A malformed row surfaces an error no later than done() and nothing
 *       is committed.
 *   9.  Single-active-statement: a query on the same connection is rejected
 *       while an insert stream is open, and works again after finish.
 *   10. cancel is idempotent; cancel-then-destroy releases the stream and
 *       the connection stays usable for queries and a fresh stream.
 *   11. Init errors (bad target table) surface via chdb_stream_insert_error
 *       on a non-NULL handle.
 *   12. destroy without done/cancel implicitly cancels: nothing committed,
 *       the single-active-statement slot is released.
 *   13. NULL-argument hardening across the whole ABI surface.
 *   14. INSERT INTO FUNCTION file(...) target: stream, finish, read back.
 *   15. Parquet input (non-streamable format): chunks buffered until done,
 *       exact values — payload generated by chdb itself via FORMAT Parquet.
 *
 * Build (against an already-built libchdb.so):
 *   clang examples/chdbStreamInsertTest.c -I./programs/local \
 *         -L. -lchdb -o examples/chdbStreamInsertTest
 *   LD_LIBRARY_PATH=. ./examples/chdbStreamInsertTest
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <inttypes.h>

#include "chdb.h"

static int g_failed_assertions = 0;

#define CHECK(cond, msg)                                                   \
    do {                                                                   \
        if (!(cond)) {                                                     \
            fprintf(stderr, "  ASSERT FAIL: %s (%s:%d)\n",                 \
                    (msg), __FILE__, __LINE__);                            \
            g_failed_assertions += 1;                                      \
        }                                                                  \
    } while (0)

/* Runs a query, asserts it succeeded, and returns the result handle. */
static chdb_result * run(chdb_connection conn, const char * query)
{
    chdb_result * result = chdb_query(conn, query, "CSV");
    CHECK(result != NULL, query);
    if (result) {
        const char * error = chdb_result_error(result);
        if (error) {
            fprintf(stderr, "  query error: %s\n  query: %s\n", error, query);
            g_failed_assertions += 1;
        }
    }
    return result;
}

/* Runs a query and asserts its CSV output equals `expected`. */
static void expect_query(chdb_connection conn, const char * query, const char * expected)
{
    chdb_result * result = run(conn, query);
    if (!result)
        return;
    char * buf = chdb_result_buffer(result);
    size_t len = chdb_result_length(result);
    int matches = buf && len == strlen(expected) && memcmp(buf, expected, len) == 0;
    if (!matches) {
        fprintf(stderr, "  MISMATCH for %s\n    expected: %s    got: %.*s\n",
                query, expected, (int)(len > 256 ? 256 : len), buf ? buf : "(null)");
        g_failed_assertions += 1;
    }
    chdb_destroy_query_result(result);
}

/* Runs a query returning a single integer value. Returns -1 on failure. */
static long long query_int(chdb_connection conn, const char * query)
{
    chdb_result * result = run(conn, query);
    if (!result)
        return -1;
    char * buf = chdb_result_buffer(result);
    long long value = buf ? atoll(buf) : -1;
    chdb_destroy_query_result(result);
    return value;
}

/* Streams `rows` one-row CSV appends of the numbers 0..rows-1. Returns 0 on
 * the first append failure (after recording it). */
static int append_numbers_csv(chdb_insert_stream stream, uint64_t rows)
{
    char row[32];
    for (uint64_t i = 0; i < rows; i++) {
        int len = snprintf(row, sizeof(row), "%" PRIu64 "\n", i);
        if (chdb_stream_append(stream, row, (size_t)len) != CHDBSuccess) {
            const char * err = chdb_stream_insert_error(stream);
            fprintf(stderr, "  append failed at row %" PRIu64 ": %s\n",
                    i, err ? err : "(no message)");
            g_failed_assertions += 1;
            return 0;
        }
    }
    return 1;
}

static void test_full_lifecycle(chdb_connection conn)
{
    printf("== test_full_lifecycle ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st1 (a UInt64, b String) ENGINE = Memory"));

    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st1 (a, b)", "CSV");
    CHECK(stream != NULL, "stream handle is non-NULL");
    CHECK(chdb_stream_insert_error(stream) == NULL, "no init error");

    CHECK(chdb_stream_append(stream, "1,one\n", 6) == CHDBSuccess, "append #1");
    CHECK(chdb_stream_append(stream, "2,two\n", 6) == CHDBSuccess, "append #2");

    chdb_result * result = chdb_stream_done(stream);
    CHECK(result != NULL, "done returns a result");
    if (result) {
        CHECK(chdb_result_error(result) == NULL, "done reports no error");
        CHECK(chdb_result_rows_written(result) == 2, "rows_written == 2");
        CHECK(chdb_result_bytes_written(result) > 0, "bytes_written > 0");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream);

    expect_query(conn, "SELECT a, b FROM st1 ORDER BY a", "1,\"one\"\n2,\"two\"\n");
}

/* One helper for the per-format tests: stream two rows in `format`, finish,
 * and verify the exact table contents. */
static void format_roundtrip(chdb_connection conn, const char * table,
                             const char * format, const char * payload)
{
    char query[128];
    snprintf(query, sizeof(query), "CREATE TABLE %s (a UInt64, b String) ENGINE = Memory", table);
    chdb_destroy_query_result(run(conn, query));

    snprintf(query, sizeof(query), "INSERT INTO %s (a, b)", table);
    chdb_insert_stream stream = chdb_stream_insert(conn, query, format);
    CHECK(stream != NULL, "stream handle is non-NULL");
    const char * init_err = chdb_stream_insert_error(stream);
    if (init_err) {
        fprintf(stderr, "  init error for format %s: %s\n", format, init_err);
        g_failed_assertions += 1;
        chdb_destroy_insert_stream(stream);
        return;
    }

    CHECK(chdb_stream_append(stream, payload, strlen(payload)) == CHDBSuccess, format);

    chdb_result * result = chdb_stream_done(stream);
    if (result) {
        const char * err = chdb_result_error(result);
        if (err) {
            fprintf(stderr, "  done error for format %s: %s\n", format, err);
            g_failed_assertions += 1;
        }
        CHECK(chdb_result_rows_written(result) == 2, "rows_written == 2");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream);

    snprintf(query, sizeof(query), "SELECT a, b FROM %s ORDER BY a", table);
    expect_query(conn, query, "1,\"one\"\n2,\"two\"\n");
}

static void test_format_matrix(chdb_connection conn)
{
    printf("== test_format_matrix (TSV / JSONEachRow / Values) ==\n");
    format_roundtrip(conn, "stf_tsv", "TSV", "1\tone\n2\ttwo\n");
    /* JSONEachRow is the regression format for the parallel-parsing init
     * hang: with input_format_parallel_parsing left on, init never returns. */
    format_roundtrip(conn, "stf_json", "JSONEachRow",
                     "{\"a\":1,\"b\":\"one\"}\n{\"a\":2,\"b\":\"two\"}\n");
    format_roundtrip(conn, "stf_values", "Values", "(1,'one'),(2,'two')");
}

static void test_multi_chunk_streaming(chdb_connection conn)
{
    printf("== test_multi_chunk_streaming ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE st2 (a UInt64) ENGINE = MergeTree ORDER BY a"));

    chdb_insert_stream stream = chdb_stream_insert(conn, "INSERT INTO st2 (a)", "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");

    /* One row per append: the shape of a record-by-record producer. */
    const uint64_t n = 20000;
    append_numbers_csv(stream, n);

    chdb_result * result = chdb_stream_done(stream);
    CHECK(result != NULL, "done returns a result");
    if (result) {
        CHECK(chdb_result_error(result) == NULL, "done reports no error");
        CHECK(chdb_result_rows_written(result) == n, "rows_written == n");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream);

    /* sum(0..n-1) = n*(n-1)/2 */
    expect_query(conn, "SELECT count(), sum(a) FROM st2", "20000,199990000\n");
}

static void test_multi_block_streaming_parts(chdb_connection conn)
{
    printf("== test_multi_block_streaming_parts ==\n");
    chdb_destroy_query_result(run(conn, "CREATE TABLE stp (a UInt64) ENGINE = MergeTree ORDER BY a"));

    /* Small insert blocks force the worker to push multiple blocks through
     * sendData as appends arrive; each block lands as a separate part. With
     * default (~1M-row) blocks this data would coalesce into one part. */
    chdb_insert_stream stream = chdb_stream_insert(
        conn,
        "INSERT INTO stp (a) SETTINGS max_insert_block_size=10000, "
        "min_insert_block_size_rows=10000, min_insert_block_size_bytes=0",
        "CSV");
    CHECK(stream != NULL && chdb_stream_insert_error(stream) == NULL, "init ok");

    const uint64_t n = 50000;
    append_numbers_csv(stream, n);

    chdb_result * result = chdb_stream_done(stream);
    if (result) {
        CHECK(chdb_result_error(result) == NULL, "done reports no error");
        CHECK(chdb_result_rows_written(result) == n, "rows_written == n");
        chdb_destroy_query_result(result);
    }
    chdb_destroy_insert_stream(stream);

    long long parts = query_int(conn,
        "SELECT count() FROM system.parts WHERE table='stp' AND active");
    CHECK(parts >= 2, "expected >= 2 parts => multiple streamed blocks");
    expect_query(conn, "SELECT count(), sum(a) FROM stp", "50000,1249975000\n");
}

